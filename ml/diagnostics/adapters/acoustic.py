"""Wrap the existing acoustic CLI output without changing that pipeline."""

from __future__ import annotations

import argparse
from datetime import datetime
import json
from pathlib import Path
import subprocess
import sys
import uuid
from typing import Any

from ..schema import validate_prediction


def _check_interval(start_utc: str | None, end_utc: str | None) -> dict[str, str | None]:
    if (start_utc is None) != (end_utc is None):
        raise ValueError("provide both --start-utc and --end-utc, or neither")
    if start_utc is None:
        return {"start_utc": None, "end_utc": None}
    for name, value in (("start_utc", start_utc), ("end_utc", end_utc)):
        try:
            parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        except ValueError as exc:
            raise ValueError(f"{name} must be an ISO-8601 date-time") from exc
        if parsed.tzinfo is None or parsed.utcoffset() is None:
            raise ValueError(f"{name} must include a timezone")
    return {"start_utc": start_utc, "end_utc": end_utc}


def wrap_acoustic_output(
    native: dict[str, Any],
    *,
    prediction_id: str | None = None,
    event_id: str | None = None,
    engine_id: str | None = None,
    session_id: str | None = None,
    start_utc: str | None = None,
    end_utc: str | None = None,
) -> dict[str, Any]:
    """Map the acoustic CLI's current JSON into a validated envelope."""
    interval = _check_interval(start_utc, end_utc)
    rpm_value = native.get("predicted_rpm")
    rpm = None if rpm_value is None else {
        "value": rpm_value,
        "confidence": native.get("rpm_confidence"),
        "source": "acoustic_model",
    }
    raw_score = native.get("acoustic_novelty_score")
    raw_threshold = native.get("novelty_threshold")
    raw_alert = native.get("is_acoustically_unusual")
    anomaly = None
    if raw_score is not None and raw_threshold is not None and raw_alert is not None:
        anomaly = {
            "score": raw_score,
            "threshold": raw_threshold,
            "is_unusual": raw_alert,
            "score_name": "acoustic_novelty_score",
        }
    limitations = list(native.get("limitations", []))
    limitations.append("Signal quality was not assessed by the existing acoustic inference CLI.")
    if event_id is None or engine_id is None or session_id is None or interval["start_utc"] is None:
        limitations.append("Acquisition linkage metadata was not supplied; this result cannot establish cross-sensor synchronization.")
    result = {
        "schema_version": "1.0",
        "prediction_id": prediction_id or str(uuid.uuid4()),
        "event_id": event_id,
        "sensor_type": "acoustic",
        "status": "available",
        "engine_id": engine_id,
        "session_id": session_id,
        "measurement_interval": interval,
        "rpm": rpm,
        "anomaly": anomaly,
        "fault_prediction": native.get("fault_prediction"),
        "fault_probabilities": None,
        "signal_quality": {"status": "not_assessed", "metrics": {}},
        "model_version": native.get("model_version"),
        "limitations": limitations,
        "error": None,
        "native_output": native,
    }
    return validate_prediction(result)


def _error_envelope(message: str, *, prediction_id: str, event_id: str | None, engine_id: str | None,
                    session_id: str | None, interval: dict[str, str | None]) -> dict[str, Any]:
    return validate_prediction({
        "schema_version": "1.0", "prediction_id": prediction_id, "event_id": event_id,
        "sensor_type": "acoustic", "status": "error", "engine_id": engine_id,
        "session_id": session_id, "measurement_interval": interval,
        "rpm": None, "anomaly": None, "fault_prediction": None,
        "fault_probabilities": None,
        "signal_quality": {"status": "unavailable", "metrics": {}},
        "model_version": None, "limitations": ["Acoustic inference did not produce a prediction."],
        "error": {"code": "acoustic_inference_failed", "message": message}, "native_output": None,
    })


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("audio", type=Path)
    parser.add_argument("--event-id", help="Acquisition-provided event ID; never generated by this adapter")
    parser.add_argument("--engine-id", help="Acquisition-provided engine or vehicle ID")
    parser.add_argument("--session-id", help="Acquisition-provided recording session ID")
    parser.add_argument("--start-utc", help="Acquisition start time in ISO-8601 with timezone")
    parser.add_argument("--end-utc", help="Acquisition end time in ISO-8601 with timezone")
    parser.add_argument("--rpm-model", type=Path, default=Path("ml/saved_models/acoustic_hlcead_rpm.joblib"))
    parser.add_argument("--novelty-model", type=Path, default=Path("ml/saved_models/acoustic_hlcead_novelty.joblib"))
    parser.add_argument("--output", type=Path, help="Optional envelope JSON path; default writes to stdout")
    args = parser.parse_args()

    root = Path(__file__).resolve().parents[3]
    interval = _check_interval(args.start_utc, args.end_utc)
    prediction_id = str(uuid.uuid4())
    native_command = [
        sys.executable, str(root / "ml" / "acoustic" / "predict.py"), str(args.audio.resolve()),
        "--rpm-model", str((root / args.rpm_model).resolve() if not args.rpm_model.is_absolute() else args.rpm_model),
        "--novelty-model", str((root / args.novelty_model).resolve() if not args.novelty_model.is_absolute() else args.novelty_model),
    ]
    completed = subprocess.run(native_command, cwd=root, capture_output=True, text=True, check=False)
    if completed.returncode == 0:
        try:
            native = json.loads(completed.stdout)
            envelope = wrap_acoustic_output(
                native, prediction_id=prediction_id, event_id=args.event_id,
                engine_id=args.engine_id, session_id=args.session_id,
                start_utc=args.start_utc, end_utc=args.end_utc,
            )
        except (json.JSONDecodeError, TypeError, ValueError) as exc:
            envelope = _error_envelope(
                f"Could not adapt acoustic output: {exc}", prediction_id=prediction_id,
                event_id=args.event_id, engine_id=args.engine_id, session_id=args.session_id,
                interval=interval,
            )
    else:
        detail = completed.stderr.strip() or completed.stdout.strip() or f"exit code {completed.returncode}"
        envelope = _error_envelope(
            detail, prediction_id=prediction_id, event_id=args.event_id,
            engine_id=args.engine_id, session_id=args.session_id, interval=interval,
        )

    encoded = json.dumps(envelope, indent=2)
    if args.output:
        output_path = args.output if args.output.is_absolute() else root / args.output
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(encoded + "\n", encoding="utf-8")
    else:
        print(encoded)
    return 0 if envelope["status"] == "available" else 1


if __name__ == "__main__":
    raise SystemExit(main())
